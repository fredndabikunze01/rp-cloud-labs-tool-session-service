-- V1: Create the initial Tool-Session Service schema

CREATE TABLE colleges (
    college_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    college_name VARCHAR(150) NOT NULL UNIQUE
);

CREATE TABLE students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    college_id BIGINT NOT NULL,
    account_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    CONSTRAINT fk_students_colleges FOREIGN KEY (college_id) REFERENCES colleges (college_id),
    CONSTRAINT chk_student_account_status CHECK (
        account_status IN (
            'PENDING',
            'VALIDATED',
            'SUSPENDED'
        )
    )
);

CREATE TABLE tools (
    tool_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT
);

CREATE TABLE tool_sessions (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL,
    tool_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'REQUESTED',
    start_time TIMESTAMP,
    end_time TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sessions_students FOREIGN KEY (student_id) REFERENCES students (student_id),
    CONSTRAINT fk_sessions_tools FOREIGN KEY (tool_id) REFERENCES tools (tool_id),
    CONSTRAINT chk_session_status CHECK (
        status IN (
            'REQUESTED',
            'APPROVED',
            'REJECTED',
            'ACTIVE',
            'COMPLETED'
        )
    ),
    CONSTRAINT chk_session_times CHECK (
        end_time IS NULL
        OR start_time IS NULL
        OR end_time >= start_time
    )
);

-- Indexes for commonly queried relationships
CREATE INDEX idx_students_college ON students (college_id);

CREATE INDEX idx_sessions_student ON tool_sessions (student_id);

CREATE INDEX idx_sessions_tool ON tool_sessions (tool_id);

CREATE INDEX idx_sessions_status ON tool_sessions (status);